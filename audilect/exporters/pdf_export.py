class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to calculate total page count and draw clean running headers and footers.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running header (pages 2+)
        if self._pageNumber > 1:
            title_text = getattr(self, "doc_title", "Audilect Study Guide")
            if len(title_text) > 60:
                title_text = title_text[:57] + "..."
            self.drawString(36, 11 * inch - 28, title_text.upper())
            self.drawRightString(8.5 * inch - 36, 11 * inch - 28, "AUDILECT COMPREHENSIVE STUDY GUIDE")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(36, 11 * inch - 32, 8.5 * inch - 36, 11 * inch - 32)

        # Running footer (all pages)
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(8.5 * inch - 36, 24, page_str)
        self.drawString(36, 24, "Generated by Audilect — Active Cognitive Lecture Cockpit")
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(36, 32, 8.5 * inch - 36, 32)

        self.restoreState()


def format_ts(seconds: float) -> str:
    if seconds is None or seconds < 0:
        return "00:00"
    m = int(seconds // 60)
    s = int(seconds % 60)
    return f"{m:02d}:{s:02d}"


def sanitize_text(text: Any) -> str:
    if not text:
        return ""
    text_str = str(text)
    # Strip any brackets notes or leftover emojis
    text_str = re.sub(r'\(not in lecture\)', '', text_str, flags=re.IGNORECASE)
    # Escape XML entities for ReportLab
    return html.escape(text_str.strip())


def generate_pdf_study_guide(session_data: Dict[str, Any], output_path: str) -> str:
    """
    Generates a publication-grade, comprehensive study guide PDF for a lecture session:
    1. Title Banner & Session Metadata
    2. Executive Synthesis & Topic Outline
    3. Core Concept Glossary (Definitions)
    4. Socratic Active Recall Questions & Explanations
    5. Full Chronological Annotated Transcript with Outside Knowledge Callouts
    """
    doc = SimpleDocTemplate(
        output_path,
        pagesize=letter,
        leftMargin=36,
        rightMargin=36,
        topMargin=42,
        bottomMargin=42
    )

    video_title = session_data.get("video_title", "Lecture")
    duration_str = session_data.get("duration_formatted") or format_ts(session_data.get("duration", 0))
    created_at_raw = session_data.get("created_at")
    date_str = datetime.now().strftime("%B %d, %Y")
    if created_at_raw:
        try:
            date_str = datetime.fromtimestamp(created_at_raw).strftime("%B %d, %Y")
        except Exception:
            pass

    topic_blocks = session_data.get("topic_blocks", [])
    concept_anchors = session_data.get("concept_anchors", [])
    checkpoints = session_data.get("checkpoints", [])
    segments = session_data.get("segments", [])
    total_words = session_data.get("total_words") or sum(len(s.get("text", "").split()) for s in segments)
    total_elabs = sum(1 for s in segments if s.get("ai_elaboration"))

    # Styles
    styles = getSampleStyleSheet()

    c_dark = colors.HexColor("#0F172A")
    c_subtext = colors.HexColor("#475569")
    c_blue = colors.HexColor("#2563EB")
    c_border = colors.HexColor("#CBD5E1")

    title_style = ParagraphStyle(
        "CoverTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=colors.white,
        spaceAfter=4
    )

    subtitle_style = ParagraphStyle(
        "CoverSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=13,
        textColor=colors.HexColor("#94A3B8")
    )

    h1_style = ParagraphStyle(
        "SectionH1",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=16,
        textColor=c_dark,
        spaceBefore=14,
        spaceAfter=6,
        keepWithNext=True
    )

    body_style = ParagraphStyle(
        "BodyTextCustom",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#1E293B")
    )

    meta_label = ParagraphStyle(
        "MetaLabel",
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#64748B")
    )

    meta_val = ParagraphStyle(
        "MetaVal",
        fontName="Helvetica-Bold",
        fontSize=10,
        leading=12,
        textColor=c_dark
    )

    concept_term_style = ParagraphStyle(
        "ConceptTerm",
        fontName="Helvetica-Bold",
        fontSize=10,
        leading=13,
        textColor=c_blue
    )

    q_title_style = ParagraphStyle(
        "QTitle",
        fontName="Helvetica-Bold",
        fontSize=9.5,
        leading=13,
        textColor=c_dark
    )

    opt_style = ParagraphStyle(
        "OptText",
        fontName="Helvetica",
        fontSize=8.5,
        leading=11.5,
        textColor=colors.HexColor("#334155")
    )

    opt_correct_style = ParagraphStyle(
        "OptCorrectText",
        fontName="Helvetica-Bold",
        fontSize=8.5,
        leading=11.5,
        textColor=colors.HexColor("#15803D")
    )

    exp_style = ParagraphStyle(
        "ExpText",
        fontName="Helvetica-Oblique",
        fontSize=8.5,
        leading=11.5,
        textColor=colors.HexColor("#1E293B")
    )

    ts_style = ParagraphStyle(
        "TimestampStyle",
        fontName="Courier-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#475569")
    )

    callout_badge_style = ParagraphStyle(
        "CalloutBadge",
        fontName="Helvetica-Bold",
        fontSize=7.5,
        leading=9,
        textColor=colors.HexColor("#0F172A")
    )

    callout_text_style = ParagraphStyle(
        "CalloutText",
        fontName="Helvetica",
        fontSize=8.5,
        leading=11.5,
        textColor=colors.HexColor("#1E293B")
    )

    elements = []

    # -------------------------------------------------------------
    # 1. HEADER HERO BANNER
    # -------------------------------------------------------------
    banner_cell = [
        Paragraph(sanitize_text(video_title), title_style),
        Paragraph("AUDILECT COMPREHENSIVE ACTIVE STUDY GUIDE & COMPLETE TRANSCRIPT", subtitle_style)
    ]
    banner_table = Table([[banner_cell]], colWidths=[7.5 * inch])
    banner_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#0F172A")),
        ("PADDING", (0, 0), (-1, -1), 14),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 14),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    elements.append(banner_table)
    elements.append(Spacer(1, 8))

    # -------------------------------------------------------------
    # STATS & METADATA BAR
    # -------------------------------------------------------------
    meta_data = [
        [
            Paragraph("DATE", meta_label),
            Paragraph("DURATION", meta_label),
            Paragraph("TOTAL WORDS", meta_label),
            Paragraph("CHECKPOINTS", meta_label),
            Paragraph("CONCEPTS", meta_label),
            Paragraph("AI CALLOUTS", meta_label),
        ],
        [
            Paragraph(date_str, meta_val),
            Paragraph(duration_str, meta_val),
            Paragraph(f"{total_words:,}", meta_val),
            Paragraph(f"{len(checkpoints)} Qs", meta_val),
            Paragraph(f"{len(concept_anchors)} Terms", meta_val),
            Paragraph(f"{total_elabs} Notes", meta_val),
        ]
    ]
    meta_table = Table(meta_data, colWidths=[1.25 * inch] * 6)
    meta_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("PADDING", (0, 0), (-1, -1), 5),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
    ]))
    elements.append(meta_table)
    elements.append(Spacer(1, 14))

    # -------------------------------------------------------------
    # 2. TOPIC OUTLINE / EXECUTIVE SYNTHESIS
    # -------------------------------------------------------------
    if topic_blocks:
        elements.append(Paragraph("1. LECTURE TOPIC ROADMAP", h1_style))
        elements.append(HRFlowable(width="100%", thickness=1, color=c_blue, spaceBefore=2, spaceAfter=6))

        outline_rows = [
            [Paragraph("TIME", meta_label), Paragraph("TOPIC / CORE FOCUS", meta_label), Paragraph("KEY DISCUSSION", meta_label)]
        ]
        for b in topic_blocks:
            t_str = format_ts(b.get("start", 0))
            title = sanitize_text(b.get("title", "Topic"))
            summary = sanitize_text(b.get("summary") or b.get("full_text", "")[:130] + "...")
            outline_rows.append([
                Paragraph(t_str, ts_style),
                Paragraph(title, ParagraphStyle("BoldOutline", parent=body_style, fontName="Helvetica-Bold")),
                Paragraph(summary, body_style)
            ])

        outline_table = Table(outline_rows, colWidths=[0.8 * inch, 2.2 * inch, 4.5 * inch])
        outline_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F1F5F9")),
            ("LINEBELOW", (0, 0), (-1, 0), 1, colors.HexColor("#CBD5E1")),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("PADDING", (0, 0), (-1, -1), 4),
        ]))
        elements.append(outline_table)
        elements.append(Spacer(1, 14))

    # -------------------------------------------------------------
    # 3. CORE CONCEPT GLOSSARY & DEFINITIONS
    # -------------------------------------------------------------
    if concept_anchors:
        elements.append(KeepTogether([
            Paragraph("2. CORE CONCEPTS & DEFINITIONS", h1_style),
            HRFlowable(width="100%", thickness=1, color=c_blue, spaceBefore=2, spaceAfter=6)
        ]))

        concept_rows = []
        for idx, c in enumerate(concept_anchors):
            term = sanitize_text(c.get("term", f"Concept {idx+1}"))
            primer = sanitize_text(c.get("primer", ""))
            ts = format_ts(c.get("timestamp", 0))

            header_p = Paragraph(f"<b>{idx+1}. {term}</b> <font color='#64748B'>[{ts}]</font>", concept_term_style)
            primer_p = Paragraph(primer, body_style)

            card_table = Table([[header_p], [primer_p]], colWidths=[7.5 * inch])
            card_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ("PADDING", (0, 0), (-1, -1), 6),
                ("TOPPADDING", (0, 0), (-1, 0), 6),
                ("BOTTOMPADDING", (0, 1), (-1, 1), 6),
            ]))
            concept_rows.append(card_table)
            concept_rows.append(Spacer(1, 5))

        elements.extend(concept_rows)
        elements.append(Spacer(1, 10))

    # -------------------------------------------------------------
    # 4. SOCRATIC ACTIVE RECALL & CHECKPOINTS
    # -------------------------------------------------------------
    if checkpoints:
        elements.append(KeepTogether([
            Paragraph("3. SOCRATIC ACTIVE RECALL & SELF-TEST QUESTIONS", h1_style),
            HRFlowable(width="100%", thickness=1, color=c_blue, spaceBefore=2, spaceAfter=6),
            Paragraph("Test your conceptual retention. Questions emphasize cause, trade-offs, and critical mechanisms.", subtitle_style),
            Spacer(1, 6)
        ]))

        q_elements = []
        letters = ["A", "B", "C", "D"]
        for idx, q in enumerate(checkpoints):
            q_text = sanitize_text(q.get("question", ""))
            opts = q.get("options", [])
            correct_idx = q.get("correct_index", 0)
            exp = sanitize_text(q.get("explanation", ""))
            ts = format_ts(q.get("timestamp", 0))

            q_title = Paragraph(f"<b>Q{idx+1} [{ts}]:</b> {q_text}", q_title_style)

            opt_paragraphs = []
            for o_idx, opt in enumerate(opts[:4]):
                prefix = f"<b>{letters[o_idx]}.</b> "
                opt_str = sanitize_text(opt)
                if o_idx == correct_idx:
                    p = Paragraph(f"{prefix}{opt_str} <font color='#15803D'>[CORRECT ANSWER]</font>", opt_correct_style)
                else:
                    p = Paragraph(f"{prefix}{opt_str}", opt_style)
                opt_paragraphs.append([p])

            opts_subtable = Table(opt_paragraphs, colWidths=[7.2 * inch])
            opts_subtable.setStyle(TableStyle([
                ("PADDING", (0, 0), (-1, -1), 2),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ]))

            exp_p = Paragraph(f"<b>Explanation:</b> {exp}", exp_style)

            card_content = [
                [q_title],
                [Spacer(1, 3)],
                [opts_subtable],
                [Spacer(1, 3)],
                [exp_p]
            ]
            card = Table(card_content, colWidths=[7.5 * inch])
            card.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#FAFAFA")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                ("PADDING", (0, 0), (-1, -1), 6),
            ]))

            q_elements.append(KeepTogether(card))
            q_elements.append(Spacer(1, 6))

        elements.extend(q_elements)
        elements.append(Spacer(1, 10))

    # -------------------------------------------------------------
    # 5. FULL CHRONOLOGICAL ANNOTATED TRANSCRIPT
    # -------------------------------------------------------------
    if segments:
        elements.append(KeepTogether([
            Paragraph("4. COMPLETE ANNOTATED LECTURE TRANSCRIPT", h1_style),
            HRFlowable(width="100%", thickness=1, color=c_blue, spaceBefore=2, spaceAfter=6),
            Paragraph("Full verbatim timeline synchronized with high-value outside knowledge elaborations.", subtitle_style),
            Spacer(1, 6)
        ]))

        transcript_cards = []
        for s in segments:
            ts = format_ts(s.get("start", 0))
            spoken = sanitize_text(s.get("text", ""))
            elab = s.get("ai_elaboration")

            seg_elements = [
                Paragraph(f"<b>[{ts}]</b> {spoken}", body_style)
            ]

            if elab and elab.get("content"):
                raw_badge = (elab.get("badge") or elab.get("type") or "INSIGHT").upper()
                clean_badge = sanitize_text(re.sub(r'\(.*?\)', '', raw_badge).replace('[', '').replace(']', '').strip().upper())
                title = sanitize_text(elab.get("title", "Key Insight"))
                content = sanitize_text(elab.get("content", ""))

                badge_color = "#2563EB"
                bg_color = "#EFF6FF"
                border_color = "#BFDBFE"
                if "PITFALL" in clean_badge or "MISCONCEPTION" in clean_badge or "WARNING" in clean_badge:
                    clean_badge = "COMMON MISCONCEPTION"
                    badge_color = "#DC2626"
                    bg_color = "#FEF2F2"
                    border_color = "#FECACA"
                elif "APPLICATION" in clean_badge or "REAL" in clean_badge:
                    clean_badge = "PRACTICAL APPLICATION"
                    badge_color = "#059669"
                    bg_color = "#F0FDF4"
                    border_color = "#BBF7D0"
                elif "INTUITION" in clean_badge or "CONCEPT" in clean_badge:
                    clean_badge = "KEY CONCEPT"
                    badge_color = "#2563EB"
                    bg_color = "#EFF6FF"
                    border_color = "#BFDBFE"

                callout_head = Paragraph(f"<b><font color='{badge_color}'>{clean_badge}:</font></b> <b>{title}</b>", callout_badge_style)
                callout_body = Paragraph(content, callout_text_style)

                callout_table = Table([[callout_head], [callout_body]], colWidths=[7.2 * inch])
                callout_table.setStyle(TableStyle([
                    ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(bg_color)),
                    ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor(border_color)),
                    ("PADDING", (0, 0), (-1, -1), 4),
                    ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ]))

                seg_elements.append(Spacer(1, 2))
                seg_elements.append(callout_table)

            row_table = Table([[Table([[e] for e in seg_elements], colWidths=[7.4 * inch])]], colWidths=[7.5 * inch])
            row_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#FFFFFF")),
                ("LINEBELOW", (0, 0), (-1, -1), 0.5, colors.HexColor("#F1F5F9")),
                ("PADDING", (0, 0), (-1, -1), 3),
            ]))

            transcript_cards.append(row_table)

        elements.extend(transcript_cards)

    # Canvas decorator metadata
    def on_first_page(canvas_obj, document):
        canvas_obj.doc_title = video_title

    def on_later_pages(canvas_obj, document):
        canvas_obj.doc_title = video_title

    # Build the document
    doc.build(elements, canvasmaker=NumberedCanvas, onFirstPage=on_first_page, onLaterPages=on_later_pages)
    return output_path
